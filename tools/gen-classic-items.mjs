// Generates server/rpg/items/classicTemplates.js from a Daggerfall Unity checkout (MIT):
//   Assets/Resources/ItemTemplates.txt and Assets/Scripts/Game/Items/ItemEnums.cs.
// Only numeric template facts and English template names are copied (the same facts server/rpg/inventory.js
// already records by hand for weapons and armour). Usage:
//   node tools/gen-classic-items.mjs .ref/daggerfall-unity > server/rpg/items/classicTemplates.js
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.argv[2] ?? '.ref/daggerfall-unity';
const templates = JSON.parse(readFileSync(join(root, 'Assets/Resources/ItemTemplates.txt'), 'utf8'));
const enums = readFileSync(join(root, 'Assets/Scripts/Game/Items/ItemEnums.cs'), 'utf8');

// ItemGroups values (ItemEnums.cs) for the groups this module covers.
const GROUPS = {
  Drugs: 0, UselessItems1: 1, Books: 7, UselessItems2: 9, ReligiousItems: 10, Maps: 11, Paintings: 13, Gems: 14,
  PlantIngredients1: 15, PlantIngredients2: 16, CreatureIngredients1: 17, CreatureIngredients2: 18, CreatureIngredients3: 19,
  MiscellaneousIngredients1: 20, MetalIngredients: 21, MiscellaneousIngredients2: 22, Jewellery: 25, QuestItems: 26, MiscItems: 27,
};

function enumMembers(name) {
  const m = new RegExp(`public enum ${name}\\b[^{]*\\{([^}]*)\\}`).exec(enums);
  if (!m) throw new Error(`enum ${name} not found`);
  return [...m[1].matchAll(/(\w+)\s*=\s*(\d+)/g)].map(([, k, v]) => [k, +v]);
}

const byIndex = new Map(templates.map((t) => [t.index, t]));
const groups = {};
const used = new Set();
for (const [g, id] of Object.entries(GROUPS)) {
  groups[g] = { id, members: enumMembers(g).map(([, v]) => v) };
  for (const v of groups[g].members) used.add(v);
}
const rows = [...used].sort((a, b) => a - b).map((i) => {
  const t = byIndex.get(i);
  return [t.index, t.name, t.baseWeight, t.hitPoints, t.capacityOrTarget, t.basePrice, t.enchantmentPoints, t.rarity, t.variants, t.isIngredient ? 1 : 0, t.worldTextureArchive, t.worldTextureRecord];
});

const out = [];
out.push('// GENERATED by tools/gen-classic-items.mjs from Daggerfall Unity (MIT, (c) 2009-2023 Daggerfall Workshop)');
out.push('// Assets/Resources/ItemTemplates.txt and Game/Items/ItemEnums.cs at revision 3d85a283672a4955e32992097ea7719e896dbadb.');
out.push('// Facts only: template index, name, weight (kg), hit points, capacity/target, base price, enchantment points, rarity,');
out.push('// variants, ingredient flag and the world TEXTURE archive/record. Art is read in the browser from the player\'s files.');
out.push('// Do not edit by hand.');
out.push('');
out.push('/** [index, name, weight, hitPoints, capacityOrTarget, basePrice, enchantmentPoints, rarity, variants, isIngredient, worldArchive, worldRecord] */');
out.push('export const TEMPLATE_ROWS = Object.freeze([');
for (const r of rows) out.push(`  ${JSON.stringify(r)},`);
out.push(']);');
out.push('');
out.push('/** ItemGroups id and member template indices in enum order (ItemHelper.GetEnumArray). */');
out.push('export const GROUPS = Object.freeze({');
for (const [g, v] of Object.entries(groups)) out.push(`  ${g}: Object.freeze({ id: ${v.id}, members: Object.freeze(${JSON.stringify(v.members)}) }),`);
out.push('});');
process.stdout.write(`${out.join('\n')}\n`);
