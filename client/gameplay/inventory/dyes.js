export const CLOTHING_DYE_START = 0x60;
export const METAL_DYE_START = 0x70;

/** Swap the 16-colour dye band of indexed pixels in place. kind: 'clothing' | 'metal'. */
export function applyDye(data, kind, dye) {
  let start;
  let table;
  if (kind === 'clothing') {
    if (!Object.hasOwn(CLOTH_DYES, dye)) return data;
    start = CLOTHING_DYE_START;
    const base = CLOTH_DYES[dye];
    table = Array.from({ length: 16 }, (_, i) => (base + i) & 0xff);
  } else if (kind === 'metal') {
    if (!Object.hasOwn(METAL_DYES, dye)) return data;
    table = METAL_DYES[dye];
    start = METAL_DYE_START;
  } else return data;
  for (let i = 0; i < data.length; i++) {
    const c = data[i];
    if (c >= start && c <= start + 15) data[i] = table[c - start];
  }
  return data;
}
