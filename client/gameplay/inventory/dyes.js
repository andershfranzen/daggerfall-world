/*
 * Clothing dyes (DyeColors 0-9) and the first palette index of each 16-colour
 * band that replaces clothing indices 0x60-0x6F (ImageProcessing.GetDyeColorTable).
 */
export const CLOTH_DYES = Object.freeze({
  blue: 0x60, grey: 0x50, red: 0xef, brown: 0x20, purple: 0x30, tan: 0x40, white: 0x70, aquamarine: 0x80, yellow: 0x90, green: 0xa0,
});
